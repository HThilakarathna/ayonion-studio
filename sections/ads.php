<script>
    document.addEventListener('DOMContentLoaded', () => {
        // Lazy load ad videos using IntersectionObserver
        const lazyAdVideos = document.querySelectorAll("video.lazy-video-ads");
        if ("IntersectionObserver" in window) {
            const lazyVideoObserver = new IntersectionObserver((entries, observer) => {
                entries.forEach((video) => {
                    if (video.isIntersecting) {
                        const target = video.target;
                        const source = target.querySelector('source');
                        if (source && source.dataset.src) {
                            source.src = source.dataset.src;
                        }
                        target.load();
                        // Not auto-playing here since it requires a play button click in ads.php
                        lazyVideoObserver.unobserve(target);
                    }
                });
            }, { rootMargin: "0px 0px 1500px 0px" });

            lazyAdVideos.forEach((lazyVideo) => {
                lazyVideoObserver.observe(lazyVideo);
            });
        } else {
            lazyAdVideos.forEach((video) => {
                const source = video.querySelector('source');
                if (source && source.dataset.src) {
                    source.src = source.dataset.src;
                }
                video.load();
            });
        }
    });
</script>
